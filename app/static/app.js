const sessionId = crypto.randomUUID();
let state = { candidates: [], draft: null, checklist: [], policy_refs: [], management_brief: null, interview_pack: null };
let useSupervisor = true;
let recorder, chunks = [], recording = false;
const $ = (id) => document.getElementById(id);

async function request(path, options = {}) {
  const response = await fetch(path, options);
  if (!response.ok) throw new Error(await response.text());
  return response.json();
}
function addMessage(role, text) {
  const welcome = document.querySelector(".welcome");
  if (welcome) welcome.remove();
  const item = document.createElement("div");
  item.className = `message ${role}`;
  item.innerHTML = `<div class="message-label">${role === "user" ? "You" : "TalentScout HR"}</div><div class="bubble"></div>`;
  item.querySelector(".bubble").textContent = text;
  $("chat").appendChild(item);
  $("chat").scrollTop = $("chat").scrollHeight;
}
function showNotice(text) {
  $("notice").textContent = text;
  $("notice").classList.toggle("hidden", !text);
}
function renderShortlist() {
  const items = state.candidates || [];
  $("candidate-count").textContent = items.length;
  if (!items.length) {
    $("rail-content").innerHTML = `<h3 class="rail-title">Your shortlist</h3><p class="rail-copy">Describe a role to start sourcing candidates. The agent will show public evidence here.</p>`;
    return;
  }
  $("rail-content").innerHTML = `<h3 class="rail-title">Live shortlist</h3><p class="rail-copy">${items.length} profiles with transparent evidence scores.</p>` +
    items.map((c) => {
      const name = c.name || c.username || c.title || "Public profile";
      const tags = (c.matched_skills || []).slice(0, 4).map((x) => `<span class="tag">${escapeHtml(x)}</span>`).join("");
      const url = c.profile_url || c.url;
      return `<article class="candidate-card"><div class="candidate-head"><span class="candidate-name">${escapeHtml(name)}</span><span class="score">${c.match_score || 0}%</span></div><p>${escapeHtml(c.bio || c.snippet || "No public summary available.")}</p><div>${tags || '<span class="tag">Evidence pending</span>'}</div>${url ? `<a href="${escapeHtml(url)}" target="_blank" rel="noopener">Open source profile ↗</a>` : ""}</article>`;
    }).join("");
}
function renderWork() {
  const draft = state.draft;
  const checklist = state.checklist || [];
  const policies = state.policy_refs || [];
  let html = `<h3 class="rail-title">Recent work</h3><p class="rail-copy">Artifacts generated by the assistant stay here for review.</p>`;
  if (draft) html += `<article class="work-card"><strong>${escapeHtml(draft.type === "outreach" ? "Outreach draft" : "Job description")}</strong><div class="work-content">${escapeHtml(draft.content)}</div></article>`;
  if (checklist.length) html += `<article class="work-card"><strong>Onboarding checklist</strong>${checklist.map((x) => `<p class="rail-copy">○ ${escapeHtml(x.task)} <small>· ${escapeHtml(x.owner)}</small></p>`).join("")}</article>`;
  if (policies.length) html += policies.map((x) => `<article class="work-card"><strong>${escapeHtml(x.title)}</strong><p class="rail-copy">${escapeHtml(x.answer)}</p><small>Local policy reference: ${escapeHtml(x.id)}</small></article>`).join("");
  const brief = state.management_brief;
  if (brief) html += `<article class="work-card"><strong>Management brief</strong><pre class="work-content">${escapeHtml(JSON.stringify(brief, null, 2))}</pre></article>`;
  const pack = state.interview_pack;
  if (pack) html += `<article class="work-card"><strong>Interview pack</strong><pre class="work-content">${escapeHtml(JSON.stringify(pack, null, 2))}</pre></article>`;
  $("rail-content").innerHTML = html;
}
async function renderPipeline() {
  const data = await request("/api/pipeline");
  const items = data.candidates || [];
  $("rail-content").innerHTML = `<h3 class="rail-title">Review pipeline</h3><p class="rail-copy">Move candidates forward when your team has reviewed the evidence.</p>` +
    (items.length ? items.map((c) => `<article class="candidate-card"><div class="candidate-head"><span class="candidate-name">${escapeHtml(c.name || c.username || "Public profile")}</span><span class="score">${c.match_score || 0}%</span></div><select class="stage-select" data-key="${encodeURIComponent(c.candidate_key)}"><option ${c.pipeline_stage === "Sourced" ? "selected" : ""}>Sourced</option><option ${c.pipeline_stage === "Shortlisted" ? "selected" : ""}>Shortlisted</option><option ${c.pipeline_stage === "Outreach ready" ? "selected" : ""}>Outreach ready</option></select></article>`).join("") : `<p class="rail-copy">Your pipeline will appear after sourcing.</p>`);
  document.querySelectorAll(".stage-select").forEach((select) => select.onchange = async () => {
    await request(`/api/pipeline/${select.dataset.key}`, { method: "PATCH", headers: {"Content-Type": "application/json"}, body: JSON.stringify({stage: select.value}) });
  });
}
function escapeHtml(value) { const div = document.createElement("div"); div.textContent = String(value || ""); return div.innerHTML; }
function renderResult(result) {
  state = {...state, ...result};
  renderShortlist();
  const steps = result.steps || [];
  $("activity").textContent = steps.length ? `Completed: ${steps.join(" · ")}` : "";
  $("activity").classList.toggle("hidden", !steps.length);
  if (result.reply) { addMessage("assistant", result.reply); speechSynthesis.cancel(); speechSynthesis.speak(new SpeechSynthesisUtterance(result.reply)); }
}
async function sendAgent(text) {
  const message = text.trim();
  if (!message) return;
  addMessage("user", message);
  $("message").value = "";
  $("send").disabled = true;
  $("activity").textContent = "TalentScout HR is working…";
  $("activity").classList.remove("hidden");
  showNotice("");
  try { renderResult(await request("/api/agent", {method: "POST", headers: {"Content-Type": "application/json"}, body: JSON.stringify({message, session_id: sessionId, use_supervisor: useSupervisor})})); }
  catch (error) { showNotice("The assistant could not complete that request. Check that Ollama is running, then try again."); }
  finally { $("send").disabled = false; }
}
async function health() {
  try { const result = await request("/api/health"); $("status").className = `status ${result.ok ? "ok" : "error"}`; $("status").innerHTML = `<i></i> ${result.ok ? "AI connected" : "AI unavailable"}`; }
  catch { $("status").className = "status error"; $("status").innerHTML = "<i></i> API unavailable"; }
}
document.querySelectorAll("[data-prompt]").forEach((button) => button.onclick = () => { $("message").value = button.dataset.prompt; $("message").focus(); });
document.querySelectorAll(".tab").forEach((tab) => tab.onclick = async () => { document.querySelectorAll(".tab").forEach((x) => x.classList.remove("active")); tab.classList.add("active"); if (tab.dataset.tab === "shortlist") renderShortlist(); if (tab.dataset.tab === "work") renderWork(); if (tab.dataset.tab === "pipeline") await renderPipeline(); });
$("send").onclick = () => sendAgent($("message").value);
$("message").onkeydown = (event) => { if (event.key === "Enter" && !event.shiftKey) { event.preventDefault(); sendAgent($("message").value); } };
$("reset").onclick = () => { location.reload(); };
$("supervisor-mode").onchange = (event) => { useSupervisor = event.target.checked; };
$("mic").onclick = async () => {
  if (recording) { recorder.stop(); recording = false; $("mic").textContent = "●"; return; }
  try {
    const stream = await navigator.mediaDevices.getUserMedia({audio: true});
    recorder = new MediaRecorder(stream); chunks = []; recorder.ondataavailable = (event) => chunks.push(event.data);
    recorder.onstop = async () => { const form = new FormData(); form.append("audio", new Blob(chunks, {type: recorder.mimeType}), "request.webm"); try { const result = await request("/api/transcribe", {method: "POST", body: form}); if (result.text) sendAgent(result.text); } catch { showNotice("Voice transcription failed. You can type your request instead."); } stream.getTracks().forEach((track) => track.stop()); };
    recorder.start(); recording = true; $("mic").textContent = "■";
  } catch { showNotice("Microphone permission is unavailable. You can type your request instead."); }
};
health(); renderShortlist();
