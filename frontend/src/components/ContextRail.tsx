import { useCallback, useEffect, useState } from 'react'
import { fetchPipeline, patchPipelineStage } from '../api/client'
import type { Candidate, ChecklistItem, PolicyRef, SessionState } from '../types/api'
import type { RailTab } from '../constants/quickPrompts'
import { CandidateCard } from './CandidateCard'

interface ContextRailProps {
  activeTab: RailTab
  onTabChange: (tab: RailTab) => void
  session: SessionState
}

function WorkPanel({ session }: { session: SessionState }) {
  const { draft, checklist, policy_refs, management_brief, interview_pack } = session

  return (
    <>
      <h3 className="rail-title">Recent work</h3>
      <p className="rail-copy">Artifacts generated by the assistant stay here for review.</p>
      {draft?.content && (
        <article className="work-card">
          <strong>{draft.type === 'outreach' ? 'Outreach draft' : 'Job description'}</strong>
          <div className="work-content">{draft.content}</div>
        </article>
      )}
      {checklist.length > 0 && (
        <article className="work-card">
          <strong>Onboarding checklist</strong>
          {checklist.map((item: ChecklistItem) => (
            <p key={`${item.task}-${item.owner}`} className="rail-copy">
              ○ {item.task} <small>· {item.owner}</small>
            </p>
          ))}
        </article>
      )}
      {policy_refs.map((ref: PolicyRef) => (
        <article key={ref.id} className="work-card">
          <strong>{ref.title}</strong>
          <p className="rail-copy">{ref.answer}</p>
          <small>Local policy reference: {ref.id}</small>
        </article>
      ))}
      {management_brief != null && (
        <article className="work-card">
          <strong>Management brief</strong>
          <pre className="work-content">{JSON.stringify(management_brief, null, 2)}</pre>
        </article>
      )}
      {interview_pack != null && (
        <article className="work-card">
          <strong>Interview pack</strong>
          <pre className="work-content">{JSON.stringify(interview_pack, null, 2)}</pre>
        </article>
      )}
    </>
  )
}

export function ContextRail({ activeTab, onTabChange, session }: ContextRailProps) {
  const [pipeline, setPipeline] = useState<Candidate[]>([])

  const loadPipeline = useCallback(async () => {
    const data = await fetchPipeline()
    setPipeline(data.candidates || [])
  }, [])

  useEffect(() => {
    if (activeTab === 'pipeline') {
      void loadPipeline()
    }
  }, [activeTab, loadPipeline])

  const candidates = session.candidates || []

  return (
    <aside className="context panel">
      <div className="rail-tabs">
        <button
          type="button"
          className={`tab ${activeTab === 'shortlist' ? 'active' : ''}`}
          onClick={() => onTabChange('shortlist')}
        >
          Shortlist <span>{candidates.length}</span>
        </button>
        <button
          type="button"
          className={`tab ${activeTab === 'pipeline' ? 'active' : ''}`}
          onClick={() => onTabChange('pipeline')}
        >
          Pipeline
        </button>
        <button
          type="button"
          className={`tab ${activeTab === 'work' ? 'active' : ''}`}
          onClick={() => onTabChange('work')}
        >
          Work
        </button>
      </div>
      <div className="rail-content">
        {activeTab === 'shortlist' && (
          <>
            <h3 className="rail-title">{candidates.length ? 'Live shortlist' : 'Your shortlist'}</h3>
            <p className="rail-copy">
              {candidates.length
                ? `${candidates.length} profiles with transparent evidence scores.`
                : 'Describe a role to start sourcing candidates. The agent will show public evidence here.'}
            </p>
            {candidates.map((c, i) => (
              <CandidateCard key={c.profile_url || c.url || c.username || i} candidate={c} />
            ))}
          </>
        )}
        {activeTab === 'pipeline' && (
          <>
            <h3 className="rail-title">Review pipeline</h3>
            <p className="rail-copy">Move candidates forward when your team has reviewed the evidence.</p>
            {pipeline.length === 0 ? (
              <p className="rail-copy">Your pipeline will appear after sourcing.</p>
            ) : (
              pipeline.map((c) => (
                <CandidateCard
                  key={c.candidate_key ?? c.profile_url ?? c.url}
                  candidate={c}
                  showStageSelect
                  onStageChange={(stage) => {
                    if (!c.candidate_key) return
                    void patchPipelineStage(c.candidate_key, stage).then((data) =>
                      setPipeline(data.candidates || []),
                    )
                  }}
                />
              ))
            )}
          </>
        )}
        {activeTab === 'work' && <WorkPanel session={session} />}
      </div>
    </aside>
  )
}
